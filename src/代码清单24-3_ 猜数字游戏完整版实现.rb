# chapter24_v2_full_game.rb
# 完整版猜数字游戏：双层循环实现反复玩 + 电脑提示 + 尝试次数统计

# ============================================================
# 外层循环：管理"再来一局"的游戏状态
# ============================================================
loop do
  secret = Random.rand(1..100)  # 每次新游戏都重新生成秘密数字
  attempts = 0
  hint_number = 1  # 电脑的"我猜"提示计数器

  puts "\n" + "=" * 40
  puts "【新一局】我来想一个 1-100 之间的数字..."
  puts "=" * 40

  # ============================================================
  # 内层循环：处理单局游戏的猜测逻辑
  # ============================================================
  loop do
    print "\n你猜的数字是: "
    guess = gets.chomp.to_i
    attempts += 1

    case
    when guess < secret
      # 猜小了：hint_number 是为了让电脑的"我猜"提示更自然
      puts "太小了！(提示：#{hint_number})"
      hint_number += 1
    when guess > secret
      puts "太大了！(提示：#{hint_number})"
      hint_number += 1
    else
      puts "\n恭喜你，猜对了！"
      puts "你一共用了 #{attempts} 次猜中。"
      break  # 猜对后退出内层循环，开始询问是否再来一局
    end
  end

  # ============================================================
  # 询问是否再来一局
  # ============================================================
  print "\n再来一局？(输入 y 继续，其他退出): "
  continue = gets.chomp.downcase
  break if continue != 'y' && continue != 'Y'
end

puts "\n游戏结束，感谢游玩！"