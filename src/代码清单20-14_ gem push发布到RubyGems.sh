# 首次发布需要创建账号并获取 API Key
# 1. 访问 https://rubygems.org/sign_up 注册
# 2. 访问 https://rubygems.org/settings/api-key 获取 API Key
# 3. 执行推送命令
gem push hello_gem-0.1.0.gem
# 输出：
#   Enter your RubyGems credentials.
#   Email: your.email@example.com
#   Password:
#   Pushing gem to https://rubygems.org...
#   Successfully registered gem: hello_gem (0.1.0)