# 整数除法：两个整数相除，结果仍是整数（向下取整）
a = 5 / 2
puts "整数除法: 5 / 2 = #{a}"           # => 2

# 浮点除法：只要任一操作数是浮点数，结果就是浮点数
b = 5.0 / 2
puts "浮点除法: 5.0 / 2 = #{b}"         # => 2.5

# 显式转换为浮点数后再除
c = 5.to_f / 2
puts "显式浮点: 5.to_f / 2 = #{c}"      # => 2.5

# 负数除法的差异（Ruby 3.x floor 除法 vs 截断）
d = -7 / 3
e = -7.0 / 3
puts "负数整数除法: -7 / 3 = #{d}"      # => -3（向下取整）
puts "负数浮点除法: -7.0 / 3 = #{e}"    # => -2.333...