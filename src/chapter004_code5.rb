x = 10
x += 5       # 等同于 x = x + 5
puts "x += 5 后 x = #{x}"        # => 15

y = 20
y -= 3       # 等同于 y = y - 3
puts "y -= 3 后 y = #{y}"        # => 17

z = 4
z *= 3       # 等同于 z = z * 3
puts "z *= 3 后 z = #{z}"        # => 12

n = 100
n /= 4       # 等同于 n = n / 4
puts "n /= 4 后 n = #{n}"        # => 25

m = 17
m %= 5       # 等同于 m = m % 5
puts "m %= 5 后 m = #{m}"        # => 2